import { execFileSync } from 'node:child_process';
import { statSync } from 'node:fs';
import { readFile, readdir, stat } from 'node:fs/promises';
import { basename, extname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { gzipSync } from 'node:zlib';
import { parseFrontmatter } from '../../packages/plugins/dist/index.js';

const notePattern = /\.(md|mdx|svx)$/i;
const size = (value) => ({ bytes: Buffer.byteLength(value), gzipBytes: gzipSync(value).length });

export async function audit(source, site) {
  const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: source, maxBuffer: 32 * 1024 * 1024 }).toString().split('\0').filter(Boolean);
  const visible = tracked.filter((path) => !path.split('/').some((part) => part.startsWith('.')));
  const notes = visible.filter((path) => notePattern.test(path));
  const attachments = visible.filter((path) => !notePattern.test(path) && extname(path));
  const files = [];
  // Run the same extraction hook as the build on pristine files, before publication filtering or link rewrites.
  for (const path of notes) {
    files.push({ path, extension: extname(path).toLowerCase(), content: await readFile(join(source, path), 'utf8') });
  }
  parseFrontmatter().parseFrontmatter.run({ files, meta: new Map() });
  const links = files.flatMap(({ path, rawLinks }) => rawLinks.filter(({ type }) => type === 'wikilink').map((link) => ({ path, ...link })));
  const indexPath = join(site, 'artifacts/index.ts');
  const filenames = await readdir(join(site, 'artifacts')).catch((error) => {
    if (error.code !== 'ENOENT') throw error;
    return [];
  });
  const inventory = {
    trackedNotes: tracked.filter((path) => notePattern.test(path)).length,
    visibleNotes: notes.length,
    attachments: attachments.length,
    attachmentBytes: attachments.reduce((sum, path) => sum + statSync(join(source, path)).size, 0),
    wikilinks: links.length,
    labeled: links.filter(({ label }) => label !== undefined).length,
    headings: links.filter(({ section }) => section && !section.startsWith('^')).length,
    blocks: links.filter(({ section }) => section?.startsWith('^')).length,
    embedsApprox: files.reduce((sum, { content }) => sum + [...content.matchAll(/!\[\[[^\]\n]+\]\]/g)].length, 0),
  };
  if (!filenames.includes('index.ts')) return { inventory, links };

  // These modules were generated by our build; they contain only serialized index data.
  const { index } = await import(pathToFileURL(indexPath));
  const searchPath = join(site, 'artifacts/search.ts');
  const { searchDocuments, searchIndex } = await import(pathToFileURL(searchPath));
  const entries = new Map(index.entries.map((entry) => [entry.path, entry]));
  const byHref = new Map(index.entries.map((entry) => [entry.href, entry.path]));
  const targets = new Map(index.entries.map((entry) => [entry.path, new Map(entry.links.map((link) => [link.raw, link.href]))]));
  const assetNames = new Set(index.assets.map(({ path }) => basename(path).toLowerCase()));
  const fileNames = new Set(notes.map((path) => path.replace(notePattern, '').toLowerCase()));
  const stemCounts = new Map();
  for (const path of fileNames) {
    const stem = basename(path);
    stemCounts.set(stem, (stemCounts.get(stem) ?? 0) + 1);
  }
  const aliasNames = new Set(index.entries.flatMap(({ aliases }) => aliases.map((name) => name.toLowerCase())));
  for (const link of links) {
    if (!entries.has(link.path)) continue;
    link.href = targets.get(link.path).get(link.raw) ?? null;
    link.targetPath = byHref.get(link.href) ?? null;
    link.assetCandidate = assetNames.has(basename(link.target).toLowerCase());
    const name = link.target.toLowerCase().replace(notePattern, '');
    link.aliasCandidate = aliasNames.has(name) && !fileNames.has(name) && !stemCounts.has(name);
    link.ambiguousCandidate = stemCounts.get(name) > 1;
  }
  const indexed = links.filter((link) => 'href' in link);
  const pages = [];
  for (const { href } of index.entries) {
    const html = join(site, 'dist', href, 'index.html');
    const info = await stat(html).catch((error) => {
      if (error.code !== 'ENOENT') throw error;
    });
    if (info) pages.push({ href, bytes: info.size });
  }
  pages.sort((a, b) => a.bytes - b.bytes || a.href.localeCompare(b.href));
  return {
    inventory,
    publication: {
      indexedNotes: index.entries.length,
      indexedAssets: index.assets.length,
      indexedWikilinks: indexed.length,
      withoutNoteTarget: indexed.filter(({ href }) => !href).length,
      withAssetBasename: indexed.filter(({ href, assetCandidate }) => !href && assetCandidate).length,
      localFragments: indexed.filter(({ target, section }) => !target && section).length,
      aliasCandidates: indexed.filter(({ aliasCandidate }) => aliasCandidate).length,
      ambiguousCandidates: indexed.filter(({ ambiguousCandidate }) => ambiguousCandidate).length,
      redirects: Object.keys(index.routes.redirects).length,
      graphNoteNodes: Object.keys(index.graph).length,
      graphNoteEdges: Object.values(index.graph).reduce((sum, edges) => sum + edges.length, 0),
      indexModule: size(await readFile(indexPath)),
      searchModule: size(await readFile(searchPath)),
      searchDocuments: size(JSON.stringify(searchDocuments)),
      miniSearch: size(JSON.stringify(searchIndex)),
      graphAdjacency: size(JSON.stringify(index.graph)),
      renderedNotePages: pages.length,
    },
    samplePages: pages.length ? [0.25, 0.5, 0.75].map((quantile) => pages[Math.floor(quantile * (pages.length - 1))]) : [],
    links,
  };
}
